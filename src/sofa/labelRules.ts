// Правила наклеек на детали набора для домашней сборки: группа, шаг сборки и подсказка покупателю — по серии.
// Чистый TS: правила для каждой серии; рисует наклейки Labels.tsx.

import type { SeriesId } from "./series";

export type LabelInfo = {
  /** Группа сборки: «Корпус», «Ящик 2». */
  group: string;
  /** Номер группы для цвета плашки (0 — корпус). */
  groupNo: number;
  /** Шаг сборки внутри группы и всего шагов. */
  step?: [number, number];
  /** Куда и как ставится — одна-две короткие фразы. */
  hint: string;
  /** Пара по меткам-точкам (фасад ↔ перед ящика). */
  pair?: string;
};

export type LabelRules = {
  /** Название модели на наклейке. */
  model: string;
  /** Памятка (первая наклейка). */
  memo: string[];
  info: (partId: string, name: string) => LabelInfo;
};

const shukhlyatka: LabelRules = {
  model: "ШУХЛЯТКА",
  memo: [
    "Сторона с наклейкой — внутренняя. Обратная сторона — лицо.",
    "Силуэт на наклейке — деталь, как она лежит наклейкой к вам; ▲ ВЕРХ — вверх, ▼ ПЕРЕД — к себе.",
    "Сначала соберите корпус (шаги 1–6), потом каждый ящик (шаги 1–4).",
    "Фасад и перед ящика с одинаковым числом точек — пара.",
    "Снимите наклейки перед покраской. Выборки, пазы и места под войлок и скотч не красьте.",
  ],
  info(id) {
    const d = /^d(\d)-(.+)$/.exec(id);
    if (!d) {
      const box: Record<string, [number, string]> = {
        "box-bottom": [1, "Дно корпуса. Наклейка сверху, внутрь корпуса; выборка под войлок — снизу."],
        "box-side-l": [2, "Левая стенка. Пазы для ящиков — внутрь, открытыми концами вперёд."],
        "box-strip": [3, "Стяжка: лежит плашмя, шипы на концах — в узкие пазы боковин, спереди."],
        "box-back": [4, "Задняя стенка: шипами в вырезы дна и боковин."],
        "box-side-r": [5, "Правая стенка. Пазы для ящиков — внутрь, открытыми концами вперёд."],
        "box-top": [6, "Крышка. Наклейка снизу, внутрь корпуса."],
      };
      const [step, hint] = box[id] ?? [0, ""];
      return { group: "Корпус", groupNo: 0, step: step ? [step, 6] : undefined, hint };
    }
    const n = +d[1], role = d[2];
    const dots = `${n} ${n === 1 ? "точка" : "точки"}`;
    const drawer: Record<string, [number, string]> = {
      bottom: [1, "Дно ящика. Наклейка сверху, внутрь ящика; войлочные полосы — снизу, по краям."],
      "side-l": [2, "Левая боковина ящика: шипами вниз, в прорези дна."],
      "side-r": [2, "Правая боковина ящика: шипами вниз, в прорези дна."],
      front: [3, "Перед ящика: шипами вниз. Метки и паз под винт ручки — к фасаду."],
      back: [3, "Задняя стенка ящика: шипами вниз."],
      facade: [4, "Фасад: выборкой к переду ящика. Винт ручки — в отверстие по центру."],
    };
    const [step, hint] = drawer[role] ?? [0, ""];
    const pair = role === "front" ? `к фасаду ${n} — метки: ${dots}` : role === "facade" ? `к ящику ${n} — метки: ${dots}` : undefined;
    return { group: `Ящик ${n}`, groupNo: n, step: step ? [step, 4] : undefined, hint, pair };
  },
};

/** Без своих правил — общая группа и без подсказок. */
const plain = (model: string): LabelRules => ({ model, memo: ["Сторона с наклейкой — внутренняя. Обратная сторона — лицо."], info: () => ({ group: "", groupNo: 0, hint: "" }) });

export const labelRules = (id: SeriesId, name: string): LabelRules => (id === "shukhlyatka" ? shukhlyatka : plain(name.toUpperCase()));
